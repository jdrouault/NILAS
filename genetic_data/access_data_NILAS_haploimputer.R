new_list <- set_names(map2(df_list,names(df_list),  
                           ~tibble(.x)), str_c(list_peak_names)) ###use the name to create a list that can be read through list2env, adjust the number in str_c to the number of datasets you have 

list2env(lapply(new_list, as.data.frame.list), .GlobalEnv)###bring the datasets in the env 

